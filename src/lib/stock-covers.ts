/** Full-size cover URL (what's saved on the event). */
export const stockUrl = (id: string, w = 1200) => `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=${w}&q=70`;

/** Categories with a stock set, in the order the picker shows them. */
export const STOCK_CATEGORIES = Object.keys(STOCK_IDS);

/** The category's covers (full-size URLs), or every category's when it has none. */
export function stockCovers(category: string): string[] {
  const ids = STOCK_IDS[category] ?? STOCK_IDS.Concerts;
  return ids.map((id) => stockUrl(id));
}

/** Every stock cover URL (to tell "still the stock cover" apart from an upload). */
export const ALL_STOCK = new Set(Object.values(STOCK_IDS).flat().map((id) => stockUrl(id)));

/** The default cover for a category: its first photo. */
export const defaultCover = (category: string) => stockCovers(category)[0];

/** Smaller copy of a stock URL for thumbnails. */
export const stockThumb = (url: string) => url.replace('w=1200', 'w=480');
